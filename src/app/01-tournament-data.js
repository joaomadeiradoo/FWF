// Runtime self-validation of the Annex C table. Catches accidental corruption
// (e.g. typos in edits, missing rows). Logs a warning if any issue is found.
// The slot constraints below come from the FIFA fixture template (Matches 73-88)
// and define which group's 3rd-placed team is eligible to face each group winner.
(function validateAnnexC(){
  const SLOT_ALLOWED={
    A:new Set(['C','E','F','H','I']),
    B:new Set(['E','F','G','I','J']),
    D:new Set(['B','E','F','I','J']),
    E:new Set(['A','B','C','D','F']),
    G:new Set(['A','E','H','I','J']),
    I:new Set(['C','D','F','G','H']),
    K:new Set(['D','E','I','J','L']),
    L:new Set(['E','H','I','J','K'])
  };
  const keys=Object.keys(ANNEX_C);
  if(keys.length!==495){console.warn('[ANNEX_C] expected 495 rows, got '+keys.length);return;}
  let errors=0;
  for(const k of keys){
    if(k.length!==8){console.warn('[ANNEX_C] bad key '+k);errors++;continue;}
    const row=ANNEX_C[k];
    if(typeof row!=='string'||row.length!==8){console.warn('[ANNEX_C] bad row for '+k);errors++;continue;}
    const groupSet=new Set(k);
    for(let i=0;i<8;i++){
      const winnerGrp=ANNEX_C_WINNER_ORDER[i],thirdGrp=row[i];
      if(!groupSet.has(thirdGrp)){console.warn(`[ANNEX_C] ${k}: 3${thirdGrp} not among qualifying groups`);errors++;}
      if(!SLOT_ALLOWED[winnerGrp].has(thirdGrp)){console.warn(`[ANNEX_C] ${k}: slot 1${winnerGrp} cannot host 3${thirdGrp}`);errors++;}
    }
  }
  if(errors===0) console.log('[ANNEX_C] ✓ all 495 scenarios validated');
})();

